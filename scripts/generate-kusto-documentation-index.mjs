import { access, mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tocUrl =
	'https://raw.githubusercontent.com/MicrosoftDocs/dataexplorer-docs/refs/heads/main/data-explorer/kusto-tocs/query/toc.yml';
const outputPath = resolve(projectRoot, 'src/lib/generated/kusto-documentation-index.ts');
const documentationFolder = resolve(projectRoot, 'static/kusto-docs');
const docsSiteBaseUrl = 'https://learn.microsoft.com/en-us/kusto/query';
const concurrency = 5;
const forceRefetch = process.argv
	.slice(2)
	.some((argument) => argument === '--force' || argument === '-f');
const maxRateLimitRetries = 3;

console.log(`[TOC] Downloading: ${tocUrl}`);
const response = await fetchWithRateLimitRetry(tocUrl, '[TOC]');
if (!response.ok) {
	throw new Error(
		`Unable to fetch the Kusto documentation TOC: ${response.status} ${response.statusText}`
	);
}

const index = {};
let currentName = '';
for (const line of (await response.text()).split('\n')) {
	const nameMatch = line.match(/^\s*-\s+name:\s+(.+)$/);
	if (nameMatch) {
		currentName = nameMatch[1].trim();
		continue;
	}

	const hrefMatch = line.match(/^\s*href:\s+(\/kusto\/query\/[^\s?]+)/);
	if (!hrefMatch || !currentName) {
		continue;
	}

	const path = hrefMatch[1].replace('/kusto/query/', '');
	if (!/(?:-operator|-function)$/.test(path)) {
		continue;
	}

	const label = currentName
		.toLowerCase()
		.replace(/\(\)/g, '')
		.replace(/\s+(?:operator|function)$/, '');
	if (/^[a-z0-9_-]+$/.test(label)) {
		index[label] = path;
	}

	// Retain the filename-derived key for names that do not exactly match the completion label.
	index[path.replace(/-(?:operator|function)$/, '')] ??= path;
}

const sortedIndex = Object.fromEntries(
	Object.entries(index).sort(([left], [right]) => left.localeCompare(right))
);
const documentationPaths = [...new Set(Object.values(sortedIndex))].sort();
const documentationPathsToDownload = [];

for (const path of documentationPaths) {
	if (forceRefetch) {
		documentationPathsToDownload.push(path);
		continue;
	}

	try {
		await access(resolve(documentationFolder, `${path}.md`));
	} catch {
		documentationPathsToDownload.push(path);
	}
}

await mapWithConcurrency(documentationPathsToDownload, concurrency, async (path) => {
	const documentationUrl = `${docsSiteBaseUrl}/${path}?view=microsoft-fabric&accept=text/markdown`;
	const downloadIndex = documentationPathsToDownload.indexOf(path) + 1;
	console.log(
		`[${downloadIndex}/${documentationPathsToDownload.length}] Downloading: ${path}.md (${documentationUrl})`
	);
	const response = await fetchWithRateLimitRetry(
		documentationUrl,
		`[${downloadIndex}/${documentationPathsToDownload.length}]`
	);
	if (!response.ok) {
		throw new Error(`Unable to fetch ${path}: ${response.status} ${response.statusText}`);
	}

	const outputFile = resolve(documentationFolder, `${path}.md`);
	await mkdir(dirname(outputFile), { recursive: true });
	await writeFile(outputFile, await response.text());
});

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(
	outputPath,
	`// Generated by scripts/generate-kusto-documentation-index.mjs. Do not edit manually.\n` +
		`export const KUSTO_DOCUMENTATION_PATHS = ${JSON.stringify(sortedIndex, null, '\t')} as const;\n`
);

console.log(
	`Generated ${Object.keys(sortedIndex).length} Kusto documentation paths; downloaded ${documentationPathsToDownload.length} of ${documentationPaths.length} Markdown files${forceRefetch ? ' (forced)' : ''}.`
);

async function mapWithConcurrency(items, limit, callback) {
	let nextIndex = 0;
	const workers = Array.from({ length: Math.min(limit, items.length) }, async () => {
		while (nextIndex < items.length) {
			const item = items[nextIndex++];
			if (!item) {
				return;
			}

			await callback(item);
		}
	});

	await Promise.all(workers);
}

async function fetchWithRateLimitRetry(url, progress) {
	for (let retry = 0; ; retry++) {
		const response = await fetch(url);
		if (response.status !== 429) {
			return response;
		}

		if (retry >= maxRateLimitRetries) {
			return response;
		}

		const { delay, source } = getRetryDelay(response.headers.get('retry-after'));
		console.warn(
			`${progress} Rate limited; retrying in ${formatDuration(delay)} (${source}, attempt ${retry + 1}/${maxRateLimitRetries}).`
		);
		await new Promise((resolve) => setTimeout(resolve, delay));
	}
}

function getRetryDelay(retryAfter) {
	if (retryAfter) {
		const seconds = Number(retryAfter);
		if (Number.isFinite(seconds) && seconds >= 0) {
			return { delay: seconds * 1_000, source: 'server Retry-After' };
		}

		const date = Date.parse(retryAfter);
		if (!Number.isNaN(date)) {
			return { delay: Math.max(0, date - Date.now()), source: 'server Retry-After' };
		}
	}

	return { delay: 30_000, source: 'default wait' };
}

function formatDuration(milliseconds) {
	return `${Math.ceil(milliseconds / 1_000)}s`;
}
